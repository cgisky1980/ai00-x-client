/**
 * mdToPlain — 将 Markdown 源文压成纯文本摘要（feed 卡片用）。
 *
 * 图片整段剔除；链接保留文字；代码块/行内代码保留内容；
 * 去掉强调/标题/引用/列表等行内与行首标记；HTML 标签剔除。
 */

export function mdToPlain(md: string): string {
  return md
    // 代码块 → 保留内容
    .replace(/```[^\n]*\n?([\s\S]*?)```/g, '$1')
    .replace(/~~~[^\n]*\n?([\s\S]*?)~~~/g, '$1')
    // 图片整段剔除（行内式 + 引用式）
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/!\[[^\]]*\]\[[^\]]*\]/g, '')
    // 链接 → 文字
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]+)\]\[[^\]]*\]/g, '$1')
    // 行内代码 → 内容
    .replace(/`([^`]+)`/g, '$1')
    // 强调/删除线标记
    .replace(/(\*\*|__)(.*?)\1/g, '$2')
    .replace(/(\*|_)([^*_\n]+)\1/g, '$2')
    .replace(/~~(.*?)~~/g, '$1')
    // 行首标记：标题/引用/列表/任务
    .replace(/^[ \t]{0,3}#{1,6}[ \t]+/gm, '')
    .replace(/^[ \t]{0,3}>[ \t]?/gm, '')
    .replace(/^[ \t]*[-*+][ \t]+(\[[ xX]\][ \t]+)?/gm, '')
    .replace(/^[ \t]*\d+\.[ \t]+/gm, '')
    // HTML 标签剔除
    .replace(/<[^>]+>/g, '')
    // 多余空行收敛
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
